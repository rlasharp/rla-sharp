#!/usr/bin/env python3
"""🚨 One GitHub issue for data problems, so the owner gets one notification instead of the site quietly keeping old data.
Reads data/health.json (written by the run). Problems = the run failed, the site check failed, the live site check failed,
or a data step "FAILED — kept old". Opens an issue on the first problem, comments only when the kind of problem changes,
and closes it once two runs in a row are clean. Needs GH_TOKEN (the workflow's token, issues: write) and REPO."""
import json, os, re, urllib.request
TOKEN, REPO = os.environ.get("GH_TOKEN"), os.environ.get("REPO")
TITLE = "⚠️ Data refresh problem"
FOOT = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
def api(method, path, body=None):
    r = urllib.request.Request(f"https://api.github.com/repos/{REPO}{path}", method=method, data=json.dumps(body).encode() if body is not None else None,
                               headers={"Authorization": f"Bearer {TOKEN}", "Accept": "application/vnd.github+json", "User-Agent": "rla-sharp-alert"})
    with urllib.request.urlopen(r, timeout=20) as x: return json.load(x) if x.status != 204 else None
def problems(e):
    P = []
    if not e.get("ok"): P.append("the refresh run failed")
    if e.get("check_failed"): P.append("the site check failed (new build not published)")
    if not e.get("site_ok"): P.append("live site: " + (e.get("site_issue") or "check failed"))
    for f in e.get("fails") or []:
        if "FAILED" in f: P.append(f[:160])
    return P
def main():
    if not TOKEN or not REPO: return
    H = json.load(open("data/health.json")).get("hist") or []
    if not H: return
    now, prev = problems(H[-1]), (problems(H[-2]) if len(H) > 1 else [])
    sig = sorted({re.sub(r"[:—].*", "", p).strip() for p in now})
    issues = [i for i in api("GET", "/issues?state=open&per_page=50") if i.get("title") == TITLE and "pull_request" not in i]
    iss = issues[0] if issues else None
    if now:
        body = f"**{H[-1]['at']}** ({H[-1].get('what', 'all')} update):\n" + "\n".join(f"- {p}" for p in now) + "\n\nThe site keeps the last good data for anything that failed. This issue closes itself after two clean runs.<!-- sig:" + "|".join(sig) + " -->"
        if not iss: api("POST", "/issues", {"title": TITLE, "body": body + FOOT}); print("alert: opened issue"); return
        last = (api("GET", f"/issues/{iss['number']}/comments?per_page=100") or [])
        lastsig = re.search(r"<!-- sig:(.*?) -->", (last[-1]["body"] if last else iss["body"]) or "")
        if not lastsig or lastsig.group(1) != "|".join(sig): api("POST", f"/issues/{iss['number']}/comments", {"body": body + FOOT}); print("alert: new problem commented")
    elif iss and not prev:
        api("POST", f"/issues/{iss['number']}/comments", {"body": f"✅ Two clean runs in a row (latest {H[-1]['at']}). Closing." + FOOT})
        api("PATCH", f"/issues/{iss['number']}", {"state": "closed", "state_reason": "completed"}); print("alert: closed")
try: main()
except Exception as e: print("alert:", e)
